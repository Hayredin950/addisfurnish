  /// Resolves a key and interpolates `{token}` placeholders.
  static String t(String lang, String key, [Map<String, Object>? args]) {
    final map = lang == 'am' ? am : en;
    var text = map[key] ?? en[key] ?? key;
    if (args != null) {
      for (final entry in args.entries) {
        text = text.replaceAll('{${entry.key}}', '${entry.value}');
      }
    }
    return text;
  }

  static String pluralize(String lang, int n, String singular, String plural) {
    return n == 1 ? singular : plural;
  }
}

/// Global accessor, tied to a current language value.
String tr(String lang, String key, [Map<String, Object>? args]) => I18n.t(lang, key, args);

String trList(String lang, List<String> keys) {
  for (final k in keys) {
    final v = I18n.t(lang, k);
    if (v != k) return v;
  }
  return keys.last;
}

/// A value-notifying language holder so screens rebuild on toggle.
class LanguageController extends ChangeNotifier {
  LanguageController(this._lang);

  String _lang;
  String get lang => _lang;

  set lang(String value) {
    if (_lang == value) return;
    _lang = value;
    notifyListeners();
  }

  String t(String key, [Map<String, Object>? args]) => I18n.t(_lang, key, args);
}
